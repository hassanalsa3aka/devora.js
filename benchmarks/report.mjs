#!/usr/bin/env node
/**
 * Turns the newest results/raw-*.json (or the one given) into
 * results/report.md and results/latest.json (what the docs site reads).
 * Usage: node report.mjs [results/raw-YYYY-MM-DD.json]
 */
import { readdirSync, readFileSync, writeFileSync, copyFileSync } from "node:fs";
import path from "node:path";

const HERE = path.dirname(new URL(import.meta.url).pathname);
const dir = path.join(HERE, "results");
const file =
  process.argv[2] ??
  path.join(dir, readdirSync(dir).filter((f) => /^raw-\d{4}-\d{2}-\d{2}\.json$/.test(f)).sort().pop());
const data = JSON.parse(readFileSync(file, "utf-8"));
const fws = Object.values(data.frameworks);

const ms = (n) => (n >= 1000 ? `${(n / 1000).toFixed(2)} s` : `${Math.round(n)} ms`);
const kb = (n) => `${(n / 1024).toFixed(1)} kB`;
const num = (n) => Math.round(n).toLocaleString("en-US");
const spread = (s, f) => `${f(s.min)}–${f(s.max)}`;
const label = (fw) => `${fw.name} ${fw.version}`;

function table(title, note, unit, rows, better) {
  const sorted = [...rows].sort((a, b) => (better === "lower" ? a.value - b.value : b.value - a.value));
  return [
    `### ${title}`,
    "",
    `${note} ${better === "lower" ? "Lower" : "Higher"} is better.`,
    "",
    `| Framework | ${unit} | Spread |`,
    "|---|---:|---:|",
    ...sorted.map((r) => `| ${r.fw} | ${r.shown} | ${r.spread ?? "—"} |`),
    "",
  ].join("\n");
}

const sections = [];
sections.push(
  table("Build time (cold)", "`npm run build` after deleting build output and caches. Median of the runs.", "Time",
    fws.map((f) => ({ fw: label(f), value: f.build.coldMs.median, shown: ms(f.build.coldMs.median), spread: spread(f.build.coldMs, ms) })), "lower"),
  table("Build time (warm)", "`npm run build` again right after, caches in place.", "Time",
    fws.map((f) => ({ fw: label(f), value: f.build.warmMs.median, shown: ms(f.build.warmMs.median), spread: spread(f.build.warmMs, ms) })), "lower"),
  table("Server start", "From `npm start` until `/static` answers 200.", "Time",
    fws.map((f) => ({ fw: label(f), value: f.startMs.median, shown: ms(f.startMs.median), spread: spread(f.startMs, ms) })), "lower"),
  table("Idle memory", "Resident memory of the server process tree 2 s after start (includes the `npm start` wrapper).", "RSS",
    fws.map((f) => ({ fw: label(f), value: f.idleMemoryMb.median, shown: `${f.idleMemoryMb.median.toFixed(0)} MB`, spread: spread(f.idleMemoryMb, (n) => `${n.toFixed(0)} MB`) })), "lower"),
);
for (const [key, title, note] of [
  ["static", "Requests/second: static page", "GET of the pre-rendered page."],
  ["items", "Requests/second: SSR page", "GET of the page rendered per request (loader with 100 items, one interactive counter)."],
  ["form", "Requests/second: form POST", "POST of a valid form; every framework answers 303 (Next.js: its Server Action response)."],
]) {
  sections.push(
    table(title, `${note} Median of the runs; latency is the median run's p50 / p99.`, "Requests/s",
      fws.map((f) => ({
        fw: label(f),
        value: f.load[key].rps.median,
        shown: `${num(f.load[key].rps.median)} (p50 ${f.load[key].p50.median} ms, p99 ${f.load[key].p99.median} ms)`,
        spread: spread(f.load[key].rps, num),
      })), "higher"),
  );
}
sections.push(
  table("JavaScript sent to the browser: SSR page", "Every script the `/items` page loads in Chromium, compressed here with gzip -9 (brotli in brackets).", "gzip (brotli)",
    fws.map((f) => ({ fw: label(f), value: f.browser["/items"].jsGzip, shown: `${kb(f.browser["/items"].jsGzip)} (${kb(f.browser["/items"].jsBrotli)})` })), "lower"),
  table("JavaScript sent to the browser: static page", "Same, for `/static`.", "gzip (brotli)",
    fws.map((f) => ({ fw: label(f), value: f.browser["/static"].jsGzip, shown: `${kb(f.browser["/static"].jsGzip)} (${kb(f.browser["/static"].jsBrotli)})` })), "lower"),
  table("Time until the counter responds", "From navigation start until a click on `/items`'s counter changes it, in Chromium on localhost.", "Time",
    fws.map((f) => ({ fw: label(f), value: f.browser["/items"].hydrationMs.median, shown: ms(f.browser["/items"].hydrationMs.median), spread: spread(f.browser["/items"].hydrationMs, ms) })), "lower"),
);

const m = data.machine;
const c = data.config;
const md = `# Benchmark results

Generated by \`node report.mjs\` from \`${path.relative(HERE, file)}\` — don't edit by hand.

- **Date:** ${data.date.slice(0, 10)}
- **Machine:** ${m.cpu}, ${m.cores} cores, ${m.memoryGb} GB, ${m.os}
- **Node:** ${m.node}
- **Load:** ${c.tool}, ${c.connections} connections, ${c.warmupSeconds} s warm-up, then ${c.loadRuns} runs of ${c.loadSeconds} s; client and server on the same machine
- **Builds:** ${c.buildRuns} cold + warm pairs; **starts:** ${c.startRuns}; **browser runs:** ${c.browserRuns}
- **Versions:** ${fws.map((f) => label(f) + (f.coreVersion ? ` (@devorajs/core ${f.coreVersion})` : "")).join(", ")}

${sections.join("\n")}
## Behavior checked before measuring

| Framework | Valid POST | Empty name | Shows the error |
|---|---|---|---|
${fws.map((f) => `| ${label(f)} | ${f.form.status} → ${f.form.location} | ${f.form.emptyNameStatus} | ${f.form.emptyNameShowsError ? "yes" : "no"} |`).join("\n")}

See README.md for the setup of each app and the caveats.
`;

writeFileSync(path.join(dir, "report.md"), md);
copyFileSync(file, path.join(dir, "latest.json"));
console.log(`wrote results/report.md and results/latest.json from ${path.relative(HERE, file)}`);
